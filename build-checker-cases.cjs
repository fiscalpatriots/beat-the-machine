#!/usr/bin/env node
/* Regenerates the checker's Halyard and Brightwater samples from the shared case
 * definitions in cases/, so the page and the game run the same memo version.
 *
 *   node build-checker-cases.cjs
 *
 * It rewrites the block in checker.html between BUILD:CHECKER-CASES-START and
 * BUILD:CHECKER-CASES-END and refuses to write when a card points at an account
 * the ledger does not carry, or when a case is missing its version or its date.
 * Never hand-edit the generated block. The checker holds the generated copy
 * inline rather than fetching the JSON at load, so the page still makes exactly
 * one network call, for its font, and no pasted data ever leaves the browser.
 */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const TARGET = path.join(ROOT, "checker.html");
const START = "/* BUILD:CHECKER-CASES-START */";
const END = "/* BUILD:CHECKER-CASES-END */";

const MONTHS = ["January","February","March","April","May","June","July","August","September","October","November","December"];

const CASES = [
  { key: "halyard", file: "cases/halyard-v3.json", header: ["Line", "Account", "Prior (%PRIOR%)", "Current (%CURRENT%)"],
    ratios: "Product gross margin = (4000 - 5000) / 4000" },
  { key: "brightwater", file: "cases/brightwater-v2.json", header: ["Account", "%PRIOR%", "%CURRENT%"], ratios: "" },
];

function money(v) {
  const neg = v < 0, a = Math.abs(v);
  const s = (Math.round(a * 100) / 100).toFixed(Math.abs(a - Math.round(a)) < 0.005 ? 0 : 2)
    .replace(/\B(?=(\d{3})+(?!\d))/g, ",");
  return (neg ? "-$" : "$") + s;
}
function months(c) {
  const m = MONTHS.findIndex((n) => new RegExp("\\b" + n + "\\b", "i").test(c.period));
  if (m < 0) throw new Error(c.version + ": no month named in its period, \"" + c.period + "\"");
  const year = Number(String(c.date).slice(0, 4));
  const prior = m === 0 ? { n: 11, y: year - 1 } : { n: m - 1, y: year };
  return { current: MONTHS[m] + " " + year, prior: MONTHS[prior.n] + " " + prior.y, currentMonth: MONTHS[m], year };
}
function js(s) {
  return '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\t/g, "\\t") + '"';
}

const out = [];
out.push(START);
out.push("/* Generated by build-checker-cases.cjs from the files in cases/. Do not edit by hand. */");
out.push("var CASE_SAMPLES={};");

CASES.forEach((spec) => {
  const c = JSON.parse(fs.readFileSync(path.join(ROOT, spec.file), "utf8"));
  if (!c.version || !c.date) throw new Error(spec.file + ": no version or no date");
  const mo = months(c);
  const nums = {};
  c.ledger.forEach((r) => { nums[r[0]] = r[1]; });
  c.cards.forEach((card) => {
    if (!card.acct) return;
    if (!(card.acct in nums)) throw new Error(spec.file + ": card " + card.n + " points at account " + card.acct + ", which the ledger does not carry");
    if (card.memo && card.prior != null) {
      const row = c.ledger.filter((r) => r[0] === card.acct)[0];
      if (row[2] !== card.prior || row[3] !== card.current) {
        throw new Error(spec.file + ": card " + card.n + " does not tie to the ledger row for " + card.acct);
      }
    }
  });
  const header = spec.header.map((h) => h.replace("%PRIOR%", mo.prior).replace("%CURRENT%", mo.current)).join("\t");
  const rows = c.ledger.map((r) => [r[0], r[1], money(r[2]), money(r[3])].join("\t"));
  const memo = c.cards.filter((card) => card.memo && card.memo.trim())
    .map((card) => card.n + ". " + card.memo.replace(/\s+/g, " ").trim());
  const label = c.version + " memo, " + new Date(c.date + "T12:00:00Z").getUTCDate() + " " +
    MONTHS[new Date(c.date + "T12:00:00Z").getUTCMonth()] + " " + mo.year;

  out.push("CASE_SAMPLES." + spec.key + "={");
  out.push("  ledger:[" + [header].concat(rows).map(js).join(",\n           ") + "].join(\"\\n\"),");
  out.push("  memo:[" + memo.map(js).join(",\n        ") + "].join(\"\\n\"),");
  out.push("  ratios:" + js(spec.ratios) + ",");
  out.push("  period:" + js(mo.current) + ",");
  out.push("  version:" + js(label) + ",");
  out.push("  caseVersion:" + js(c.version) + ",");
  out.push("  company:" + js(c.company) + ",");
  out.push("  lines:" + c.ledger.length + ",sentences:" + memo.length);
  out.push("};");
  console.log(spec.key + ": " + c.version + ", " + c.ledger.length + " ledger rows, " + memo.length + " memo sentences");
});
out.push(END);

const html = fs.readFileSync(TARGET, "utf8");
const i = html.indexOf(START), j = html.indexOf(END);
if (i < 0 || j < 0) throw new Error("checker.html carries no BUILD:CHECKER-CASES block");
fs.writeFileSync(TARGET, html.slice(0, i) + out.join("\n") + html.slice(j + END.length), "utf8");
console.log("checker.html samples rewritten from cases/");
